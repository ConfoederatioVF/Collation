def main():
    with open(RAW_PDF_PATH, encoding="utf-8") as f:
        raw = json.load(f)

    pdf_obs = raw["settlement_observations"]
    # Merge verified CV + flagship observations first (higher precision priority), then raw PDF observations
    merged_obs = []
    seen = set()

    for o in VERIFIED_CV_AND_FLAGSHIP_OBS + pdf_obs:
        key = (
            o["settlement_name"],
            o["year"],
            o["population"],
            o["walled_area_ha"],
            o["houses_or_compounds"],
            o["citation_short"][:40],
        )
        if key in seen:
            continue
        seen.add(key)
        merged_obs.append(o)

    # Sort cleanly by nicethi_region, settlement_name, year
    merged_obs.sort(key=lambda x: (x["nicethi_region"], x["settlement_name"], x["year"] or 9999))

    region_obs_counts = Counter(o["nicethi_region"] for o in merged_obs)
    unique_by_region = defaultdict(set)
    for o in merged_obs:
        unique_by_region[o["nicethi_region"]].add(o["settlement_name"])

    cv_unique_settlements = set()
    for im in CV_IMAGE_EXTRACTIONS:
        cv_unique_settlements.update(im["settlements_observed"])

    all_unique_settlements = set(o["settlement_name"] for o in merged_obs)

    final_doc = {
        "metadata": {
            "project": "Operation Viscount — NICETHI (Sub-Saharan Africa)",
            "archive_root": "f:/Active Projects/Project 1509 - SVEA/histmap/1.data_raw/population_regional/_references/Africa Research Files",
            "pdfs_parsed": raw["metadata"]["pdfs_parsed"],
            "pdfs_failed": raw["metadata"]["pdfs_failed"],
            "docx_parsed": raw["metadata"]["docx_parsed"],
            "cv_images_optically_inspected": len(CV_IMAGE_EXTRACTIONS),
            "cv_unique_settlements_observed_on_maps_plans": len(cv_unique_settlements),
            "total_quantitative_settlement_observations": len(merged_obs),
            "non_banned_quantitative_observations": sum(1 for o in merged_obs if not o["cites_banned_compendium"]),
            "banned_compendium_flagged_observations": sum(1 for o in merged_obs if o["cites_banned_compendium"]),
            "unique_settlements_with_quantitative_evidence": len(all_unique_settlements),
            "observations_by_nicethi_region": dict(sorted(region_obs_counts.items())),
            "unique_settlements_by_nicethi_region": {k: len(v) for k, v in sorted(unique_by_region.items())},
            "regional_population_tables_count": len(REGIONAL_POPULATION_TABLES),
            "lovejoy_oyo_docx_table_rows": len(raw.get("docx_lovejoy_oyo_table", [])),
        },
        "cv_image_extractions": CV_IMAGE_EXTRACTIONS,
        "settlement_observations": merged_obs,
        "regional_population_tables": REGIONAL_POPULATION_TABLES,
        "docx_lovejoy_oyo_timeline_sample": raw.get("docx_lovejoy_oyo_table", []),
        "top_contributing_pdfs": raw.get("parsed_pdfs_summary", [])[:50],
    }

    with open(FINAL_OUT_PATH, "w", encoding="utf-8") as f:
        json.dump(final_doc, f, ensure_ascii=False, indent=2)

    print(f"[DONE] Wrote consolidated deliverable: {FINAL_OUT_PATH}")
    print(json.dumps(final_doc["metadata"], indent=2))


if __name__ == "__main__":
    main()
