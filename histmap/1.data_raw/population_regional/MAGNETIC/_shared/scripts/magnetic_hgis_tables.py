def fix_mojibake(s):
  if not isinstance(s, str):
    return str(s or "")
  try:
    return s.encode("latin-1").decode("utf-8")
  except Exception:
    return s


def interp_dict(d, yr):
  if not d:
    return None
  pts = sorted(d.items())
  if yr <= pts[0][0]:
    return float(pts[0][1])
  if yr >= pts[-1][0]:
    return float(pts[-1][1])
  for i in range(len(pts) - 1):
    y0, v0 = pts[i]
    y1, v1 = pts[i + 1]
    if y0 <= yr <= y1:
      t = (yr - y0) / max(1.0, float(y1 - y0))
      if v0 > 0 and v1 > 0:
        return math.exp((1.0 - t) * math.log(v0) + t * math.log(v1))
      return v0 * (1.0 - t) + v1 * t
  return float(pts[-1][1])


def safe_geom(g):
  if g is None or g.is_empty:
    return None
  try:
    if not g.is_valid:
      g = make_valid(g)
    if isinstance(g, GeometryCollection):
      polys = [p for p in g.geoms if isinstance(p, (Polygon, MultiPolygon)) and not p.is_empty]
      if not polys:
        return None
      g = unary_union(polys)
    if not isinstance(g, (Polygon, MultiPolygon)) or g.is_empty:
      return None
    return g
  except Exception:
    return None


def _iter_polys(g):
  if g is None or g.is_empty:
    return
  if isinstance(g, Polygon):
    yield g
  elif isinstance(g, MultiPolygon):
    for p in g.geoms:
      if not p.is_empty:
        yield p
  elif isinstance(g, GeometryCollection):
    for p in g.geoms:
      yield from _iter_polys(p)


def cv2_rasterise_units(units, domain_mask, land_area, snap_coastal_px=3):
  """Zero-scanline, hole-aware OpenCV `cv2.fillPoly(..., shift=4)` rasteriser onto 4320x2160.

  Guarantees:
    - ZERO PIL ImageDraw horizontal scanline artefacts.
    - Interior polygon holes cut ONLY their own parent polygon (NEVER erase inner enclaves!).
    - Strict z-index ordering: lower priority painted first (atlas_defacto = Priority 0),
      higher priority painted on top (primary archival sub-administrative HGIS = Priority 2..5).
    - Optional <=3 px coastal snapping inside `domain_mask` eliminates coastal vector/raster sliver gaps.
  """
  id_grid = np.zeros((GRID_H, GRID_W), dtype=np.int32)
  scale_x = GRID_W / 360.0
  scale_y = GRID_H / 180.0
  shift_mult = 16.0  # shift=4 -> 1/16th pixel sub-pixel precision

  # Sort strictly by (priority ASC, area DESC) so fallback is bottom-most & enclaves paint on top!
  ordered = sorted(units, key=lambda u: (float(u.get("priority", 0.0)), -float(u["geom"].area)))

  for u in ordered:
    uid = int(u["id"])
    for poly in _iter_polys(u["geom"]):
      minx, miny, maxx, maxy = poly.bounds
      c0 = max(0, int(math.floor((minx + 180.0) * scale_x)) - 2)
      c1 = min(GRID_W, int(math.ceil((maxx + 180.0) * scale_x)) + 2)
      r0 = max(0, int(math.floor((90.0 - maxy) * scale_y)) - 2)
      r1 = min(GRID_H, int(math.ceil((90.0 - miny) * scale_y)) + 2)
      if c1 <= c0 or r1 <= r0:
        continue
      local_mask = np.zeros((r1 - r0, c1 - c0), dtype=np.uint8)
      ext_coords = np.asarray(poly.exterior.coords, dtype=np.float64)
      if len(ext_coords) < 3:
        continue
      px = np.round(((ext_coords[:, 0] + 180.0) * scale_x - 0.5 - c0) * shift_mult).astype(np.int32)
      py = np.round(((90.0 - ext_coords[:, 1]) * scale_y - 0.5 - r0) * shift_mult).astype(np.int32)
      cv2.fillPoly(local_mask, [np.column_stack([px, py])], 1, lineType=cv2.LINE_8, shift=4)
      for interior in poly.interiors:
        ic = np.asarray(interior.coords, dtype=np.float64)
        if len(ic) < 3:
          continue
        hx = np.round(((ic[:, 0] + 180.0) * scale_x - 0.5 - c0) * shift_mult).astype(np.int32)
        hy = np.round(((90.0 - ic[:, 1]) * scale_y - 0.5 - r0) * shift_mult).astype(np.int32)
        cv2.fillPoly(local_mask, [np.column_stack([hx, hy])], 0, lineType=cv2.LINE_8, shift=4)
      sub = id_grid[r0:r1, c0:c1]
      sub[local_mask > 0] = uid

  # Record full pre-clip area per unit for accurate straddling-province proration
  max_id = max((int(u["id"]) for u in units), default=0)
  full_area = np.bincount(id_grid.ravel(), weights=land_area.ravel().astype(np.float64), minlength=max_id + 1)

  # Clip strictly to MAGNETIC domain_mask
  id_grid[~domain_mask] = 0

  # Fill any 1-to-3 px coastal vector/raster mismatch slivers inside domain_mask via nearest painted unit
  if snap_coastal_px > 0:
    missing = domain_mask & (id_grid == 0)
    if missing.any() and (id_grid > 0).any():
      dist, idx = distance_transform_edt(id_grid == 0, return_indices=True)
      fill_mask = missing & (dist <= float(snap_coastal_px))
      if fill_mask.any():
        id_grid[fill_mask] = id_grid[idx[0][fill_mask], idx[1][fill_mask]]

  # Automated zero-scanline-defect verification inside painted Continental Europe!
  # Check if any unpainted row pixel inside domain_mask sits strictly between identical non-zero IDs above & below
  mid = id_grid[1:-1, :]
  above = id_grid[:-2, :]
  below = id_grid[2:, :]
  scanline_holes = (mid == 0) & domain_mask[1:-1, :] & (above > 0) & (above == below)
  if scanline_holes.any():
    # Heal any 1-px degenerate vertex crack (impossible with fillPoly, belt-and-suspenders guard!)
    id_grid[1:-1, :][scanline_holes] = above[scanline_holes]

  flat_ids = id_grid[domain_mask]
  flat_la = land_area[domain_mask].astype(np.float64)
  px_cnt = np.bincount(flat_ids, minlength=max_id + 1)
  area_sum = np.bincount(flat_ids, weights=flat_la, minlength=max_id + 1)

  rgba = np.zeros((GRID_H, GRID_W, 4), dtype=np.uint8)
  pos = id_grid > 0
  rgba[pos, 0] = ((id_grid[pos] >> 8) & 0xFF).astype(np.uint8)
  rgba[pos, 1] = (id_grid[pos] & 0xFF).astype(np.uint8)
  rgba[pos, 3] = 255
  return rgba, id_grid, px_cnt, area_sum, full_area


def render_europe_crop_png(id_grid, domain_mask, out_png, title_text=""):
  """Renders a high-contrast Continental Europe (+ British Isles & Scandinavia) optical QA PNG
  into `/tests/` so every single distinct boundary regime can be optically inspected."""
  # Continental Europe bbox: lon [-11, 34], lat [34.5, 71.5]
  c0 = int((-11.0 + 180.0) * GRID_W / 360.0)
  c1 = int((34.0 + 180.0) * GRID_W / 360.0)
  r0 = int((90.0 - 71.5) * GRID_H / 180.0)
  r1 = int((90.0 - 34.5) * GRID_H / 180.0)

  sub_id = id_grid[r0:r1, c0:c1]
  sub_dom = domain_mask[r0:r1, c0:c1]
  h, w = sub_id.shape

  # Vibrant deterministic per-ID colour hash (ocean = light blue, uncovered domain = bright red!)
  img = np.full((h, w, 3), [215, 232, 245], dtype=np.uint8)  # RGB ocean
  uncov = sub_dom & (sub_id == 0)
  img[uncov] = [255, 40, 40]  # Bright red highlights ANY missing coverage pixel!

  pos = sub_id > 0
  if pos.any():
    u = sub_id[pos].astype(np.uint32)
    # Deterministic high-contrast RGB hash via multiplicative mixing
    r = ((u * 2654435761) >> 16) % 190 + 50
    g = ((u * 2246822519) >> 16) % 190 + 50
    b = ((u * 3266489917) >> 16) % 190 + 50
    img[pos, 0] = r.astype(np.uint8)
    img[pos, 1] = g.astype(np.uint8)
    img[pos, 2] = b.astype(np.uint8)

  # Draw crisp 1-px dark borders between adjacent distinct IDs so every sub-admin unit stands out!
  border = np.zeros((h, w), dtype=bool)
  border[:, 1:] |= (sub_id[:, 1:] != sub_id[:, :-1]) & ((sub_id[:, 1:] > 0) | (sub_id[:, :-1] > 0))
  border[1:, :] |= (sub_id[1:, :] != sub_id[:-1, :]) & ((sub_id[1:, :] > 0) | (sub_id[:-1, :] > 0))
  img[border] = [35, 35, 42]

  # Upscale 2x with nearest-neighbour so 1-px details & borders are razor-sharp for optical inspection
  img_up = cv2.resize(img, (w * 2, h * 2), interpolation=cv2.INTER_NEAREST)
  if title_text:
    cv2.rectangle(img_up, (8, 8), (min(w * 2 - 8, 18 + len(title_text) * 11), 42), (255, 255, 255), -1)
    cv2.putText(img_up, title_text, (16, 32), cv2.FONT_HERSHEY_SIMPLEX, 0.65, (15, 15, 20), 2, cv2.LINE_AA)
  # cv2.imwrite expects BGR
  cv2.imwrite(out_png, img_up[:, :, ::-1])
