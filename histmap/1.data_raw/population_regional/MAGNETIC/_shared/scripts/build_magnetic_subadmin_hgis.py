def verify_zero_anachronisms(sy, kept_units):
  """Hard Anti-Anachronism Gatekeeper on every generated snapshot!"""
  if sy < 1990:
    nuts_bad = [u["code"] for u in kept_units if "NUTS" in u["source"] or "Roses_Wolf" in u["source"]]
    assert not nuts_bad, f"ANACHRONISM FAIL in {sy}: found NUTS/Roses-Wolf units {nuts_bad[:5]}"
  if sy <= 1980:
    flev = [u["name"] for u in kept_units if "flevoland" in u["name"].lower()]
    assert not flev, f"ANACHRONISM FAIL in {sy}: Flevoland existed only from 1986!"
  if sy < 1980:
    jura = [u["name"] for u in kept_units if u["country"] == "CH" and "jura" in u["name"].lower()]
    assert not jura, f"ANACHRONISM FAIL in {sy}: Canton Jura created only in 1979!"
  if sy <= 1970:
    metro = [u["name"] for u in kept_units if any(m in u["name"].lower() for m in ("greater manchester", "merseyside", "tyne and wear", "west midlands"))]
    assert not metro, f"ANACHRONISM FAIL in {sy}: Post-1974 UK metro counties {metro}"


def main():
  # Clean stale old rasters first so subadmin_hgis/rasters/ contains ONLY comprehensive verified snapshots
  for fn in os.listdir(RASTER_DIR):
    if fn.startswith("subadmin_id_") or fn.startswith("subadmin_meta_"):
      os.remove(os.path.join(RASTER_DIR, fn))

  dm_raw = np.asarray(Image.open(DOMAIN_MASK_PNG).convert("RGBA"), dtype=np.uint8)
  domain_mask = (dm_raw[:, :, 3] > 0) & (dm_raw[:, :, :3].sum(axis=2) > 0)
  la_raw = np.asarray(Image.open(LAND_AREA_PNG).convert("RGBA"), dtype=np.uint8)
  land_area = la_raw.reshape(-1, 4).copy().view(">u4").reshape(la_raw.shape[:2])

  src = load_all_authentic_sources()

  lit_summary = {
    "anti_anachronism_verified": True,
    "nuts_earliest_allowed_year": 1990,
    "snapshot_count": len(ALL_SNAPSHOTS),
    "generated_snapshots": {},
    "sources": [
      "HistoGIS OEAW (histogis-dump.jsonl): Holy Roman Empire Imperial Circles (1512/1555/1648/1792), Austrian Empire & Austro-Hungarian Crownlands (1815-1918), Prussian Regierungsbezirke (1820-1914)",
      "HGIS Germany (1880 & 1914) + Galloway Prussia Database (1861-1910, 12 Prussian censuses)",
      "Observatoire des Territoires / Statistique Générale de la France (SGF 1801-1925 historical département geometries & censuses) + INSEE (1876-2023)",
      "DEMOPAST University of Bologna / ISTAT Italy (11 historical province GeoJSONs & censuses, 1861-1971)",
      "mapSpainHist / INE Spain (1833 historic provinces & 15 censuses, 1857-1991)",
      "Riksarkivet swehist / SCB Sweden (authentic historic län 1750-1980)",
      "CSO Ireland CNA13 (26 historic counties, 1841-2016) & UK Parliamentary Censuses (pre-1974 historic counties, 1801-1981)",
      "BFS Switzerland (22 historic cantons pre-1979, 26 post-1979), CBS Netherlands (11 historic provinces pre-1986), INE Portugal (18 historic mainland distritos post-1835)",
      "CShapes-Europe 2.0 (ETH Zurich, 1816-2019) & aourednik/historical-basemaps (1500-1960)",
      "Eurostat GISCO NUTS-3 & demo_r_pjanaggr3 (STRICTLY 1990-2025 contemporary era only)",
    ],
  }

  lit_csv_rows = []
  print(f"\n[2] Rasterising {len(ALL_SNAPSHOTS)} comprehensive, strictly non-anachronistic HGIS regimes (1500-2020)...", flush=True)
  for sy in ALL_SNAPSHOTS:
    units = build_snapshot(sy, src)
    rgba, px_cnt, area_sum, full_area = rasterise_units(units, domain_mask, land_area)
    kept_units = []
    for u in units:
      uid = u["id"]
      if int(px_cnt[uid]) <= 0:
        continue
      in_frac = float(area_sum[uid]) / max(1.0, float(full_area[uid]))
      # Prorate ONLY straddling Imperial German (East Prussia/Kaliningrad) and Habsburg (Galicia/Bukovina)
      # sub-units where official census covers the whole province but POLARIS holds the eastern strip.
      # Do NOT prorate POLITY_HIST_POP["russia"/"ottoman empire"/"turkey"] because those totals are
      # ALREADY calibrated strictly to the MAGNETIC European territories!
      if in_frac < 0.96 and u["country"] in ("DE_IMP", "AH_IMP", "HABSBURG", "PRUSSIA", "HRE"):
        prorated_series = [[y, round(v * in_frac, 1)] for y, v in u["series"]]
      else:
        prorated_series = u["series"]
      kept_units.append({
        "id": uid, "code": u["code"], "name": u["name"], "country": u["country"],
        "source": u["source"], "is_direct_census": u["is_direct_census"],
        "pixel_count": int(px_cnt[uid]), "area_km2": round(float(area_sum[uid]), 1),
        "in_magnetic_area_frac": round(in_frac, 4),
        "series": prorated_series,
      })
      for yr_pt, pop_pt in prorated_series:
        if sy < 1990 or yr_pt == sy:
          lit_csv_rows.append([sy, u["country"], u["code"], u["name"], yr_pt, int(round(pop_pt)), round(float(area_sum[uid]), 1), u["source"]])

    verify_zero_anachronisms(sy, kept_units)

    out_png = os.path.join(RASTER_DIR, f"subadmin_id_{sy}.png")
    Image.fromarray(rgba, mode="RGBA").save(out_png, compress_level=6)
    out_meta = os.path.join(RASTER_DIR, f"subadmin_meta_{sy}.json")
    meta_obj = {
      "snapshot_year": sy, "anti_anachronism_verified": True,
      "unit_count": len(kept_units), "covered_pixels": int((rgba[:, :, 3] > 0).sum()),
      "units": kept_units,
    }
    with open(out_meta, "w", encoding="utf-8") as fh:
      json.dump(meta_obj, fh)
    lit_summary["generated_snapshots"][str(sy)] = {
      "unit_count": len(kept_units),
      "covered_pixels": meta_obj["covered_pixels"],
      "sources_used": sorted({u["source"] for u in kept_units}),
    }
    print(f"  Snapshot {sy}: {len(kept_units):4d} authentic units | {meta_obj['covered_pixels']:6,d} px | sources={len(lit_summary['generated_snapshots'][str(sy)]['sources_used'])}", flush=True)

  with open(os.path.join(HGIS_ROOT, "subadmin_enumerations_for_literature_reviews.json"), "w", encoding="utf-8") as fh:
    json.dump(lit_summary, fh, indent=2, ensure_ascii=False)
  with open(os.path.join(HGIS_ROOT, "subadmin_enumerations_for_literature_reviews.csv"), "w", newline="", encoding="utf-8") as fh:
    w = csv.writer(fh)
    w.writerow(["snapshot_regime", "country", "unit_code", "unit_name", "year", "population", "area_km2", "source"])
    w.writerows(lit_csv_rows)
  print(f"\n[DONE] Built {len(ALL_SNAPSHOTS)} strictly non-anachronistic HGIS regimes & exported {len(lit_csv_rows):,} literature-review rows.", flush=True)


if __name__ == "__main__":
  main()
