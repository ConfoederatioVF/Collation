  pt_gj = json.load(open(os.path.join(RAW_DIR, "pt_hist", "portugal_distritos.geojson"), encoding="utf-8"))
  pt_raw = {norm_str(f["properties"]["name"]): (f["properties"]["name"], safe_geom(shape(f["geometry"]))) for f in pt_gj["features"]}
  src["pt_distritos"] = pt_raw

  # 1H. UK Historic Counties (dissolving post-1974 metro counties back to pre-1974 historic counties!)
  uk_gj = json.load(open(os.path.join(RAW_DIR, "uk_hist", "uk_ceremonial_counties.geojson"), encoding="utf-8"))
  uk_hist_groups = defaultdict(list)
  for f in uk_gj["features"]:
    cn = norm_str(f["properties"].get("county") or "")
    g = safe_geom(shape(f["geometry"]))
    if g is None or not cn:
      continue
    if cn in UK_METRO_TO_HISTORIC:
      key = UK_METRO_TO_HISTORIC[cn]
    elif cn in UK_HIST_COUNTY_POP:
      key = cn
    else:
      # Group Wales & Scotland ceremonial counties into historic Wales / Scotland or match centroid
      lat = g.centroid.y
      lon = g.centroid.x
      if lat > 55.2 and lon < -1.5:
        key = "scotland"
      elif lon < -2.65 and 51.3 < lat < 53.5:
        key = "wales"
      elif lon < -5.3 and 54.0 < lat < 55.4:
        key = "northern_ireland"
      else:
        key = cn
    uk_hist_groups[key].append(g)
  uk_hist = {}
  for k, gs in uk_hist_groups.items():
    if k in UK_HIST_COUNTY_POP:
      ug = safe_geom(unary_union(gs))
      if ug is not None:
        uk_hist[k] = ug
  src["uk_hist"] = uk_hist
  print(f"  UK Pre-1974 Historic Counties: {len(uk_hist)} units (incl. Scotland, Wales, Northern Ireland & 38 historic English counties)", flush=True)

  # 1I. CSO Ireland 26 Historic Counties (unchanged since 1606) + Non-NUTS country fallback (BA/XK/MD/FO/GL)
  adm1_gj = json.load(open(NE_ADM1_GJ, encoding="utf-8"))
  ie_raw = defaultdict(list)
  for f in adm1_gj["features"]:
    p = f["properties"]
    if p.get("admin") == "Ireland":
      g = safe_geom(shape(f["geometry"]))
      if g is None:
        continue
      kn = norm_str(p.get("name", ""))
      if "dublin" in kn or "fingal" in kn or "dun laoghaire" in kn: ie_raw["dublin"].append(g)
      elif "tipperary" in kn: ie_raw["tipperary"].append(g)
      elif "laoighis" in kn or "laois" in kn: ie_raw["laois"].append(g)
      else: ie_raw[kn].append(g)
  ie_polys = {k: safe_geom(unary_union(gs)) for k, gs in ie_raw.items()}
  ie_census = defaultdict(dict)
  with open(os.path.join(RAW_DIR, "cso_ireland_cna13_1841_2016.csv"), encoding="utf-8-sig") as fh:
    for r in csv.DictReader(fh):
      if r.get("Sex") != "Both sexes":
        continue
      if r.get("STATISTIC") != "CNA13C1" and r.get("Statistic Label") != "Population":
        continue
      cname = norm_str(r.get("Province or County", ""))
      if cname not in ie_polys:
        continue
      try:
        yr, val = int(r["CensusYear"]), float(r["VALUE"])
        if val > 0:
          ie_census[cname][yr] = val
      except Exception:
        pass
  src["ie_polys"] = ie_polys
  src["ie_census"] = dict(ie_census)

  mc_gj = json.load(open(os.path.join(MAG_DIR, "_shared", "_gis_cache", "magnetic_countries.geojson"), encoding="utf-8"))
  mc_geoms = {}
  for f in mc_gj["features"]:
    adm = norm_str(f["properties"].get("ADMIN", ""))
    g = safe_geom(shape(f["geometry"]))
    if g is not None:
      mc_geoms[adm] = g
  src["mc_geoms"] = mc_geoms

  # 1J. CShapes-Europe (1816-2019) & Historical Basemaps (1500-1994)
  cs_gj = json.load(open(os.path.join(RAW_DIR, "cshapes", "CShapes-Europe.geojson"), encoding="utf-8"))
  cs_feats = []
  for f in cs_gj["features"]:
    p = f["properties"]
    try:
      y0 = int(str(p.get("From", ""))[:4])
      y1 = int(str(p.get("To", ""))[:4])
    except Exception:
      continue
    g = safe_geom(shape(f["geometry"]))
    if g is not None:
      cs_feats.append({"name": p.get("Name") or "", "norm": norm_str(p.get("Name") or ""), "y0": y0, "y1": y1, "geom": g})
  src["cshapes"] = cs_feats

  hb_map = {}
  for y in (1500, 1600, 1700, 1783, 1800, 1815, 1880, 1900, 1914, 1920, 1930, 1938, 1945, 1960):
    fp = os.path.join(RAW_DIR, "historical_basemaps", f"world_{y}.geojson")
    if os.path.isfile(fp):
      gj = json.load(open(fp, encoding="utf-8"))
      flist = []
      for f in gj["features"]:
        if not f.get("geometry"):
          continue
        g = safe_geom(shape(f["geometry"]))
        if g is None:
          continue
        minx, miny, maxx, maxy = g.bounds
        if maxx < -75 or minx > 45 or maxy < 26 or miny > 83:
          continue
        nm = f["properties"].get("NAME") or f["properties"].get("SUBJECTO") or ""
        if nm:
          flist.append({"name": nm, "norm": norm_str(nm), "geom": g})
      hb_map[y] = flist
  src["hb_map"] = hb_map
  print(f"  CShapes-Europe: {len(cs_feats)} temporalised polygons | Historical Basemaps: {len(hb_map)} epochs", flush=True)

  # 1K. Contemporary Eurostat GISCO NUTS-3 (USED STRICTLY FOR >= 1990 ONLY!)
  n3_raw = json.load(open(os.path.join(RAW_DIR, "eurostat_nuts3_2021_03m.geojson"), encoding="utf-8"))
