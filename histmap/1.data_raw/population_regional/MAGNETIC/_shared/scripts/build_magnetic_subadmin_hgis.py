def fix_mojibake(s):
  if not isinstance(s, str):
    return str(s or "")
  try:
    return s.encode("latin-1").decode("utf-8")
  except Exception:
    return s


def interp_dict(d, yr):
  if not d:
    return None
  pts = sorted(d.items())
  if yr <= pts[0][0]:
    return float(pts[0][1])
  if yr >= pts[-1][0]:
    return float(pts[-1][1])
  for i in range(len(pts) - 1):
    y0, v0 = pts[i]
    y1, v1 = pts[i + 1]
    if y0 <= yr <= y1:
      t = (yr - y0) / max(1.0, float(y1 - y0))
      if v0 > 0 and v1 > 0:
        return math.exp((1.0 - t) * math.log(v0) + t * math.log(v1))
      return v0 * (1.0 - t) + v1 * t
  return float(pts[-1][1])


def safe_geom(g):
  if g is None or g.is_empty:
    return None
  try:
    if not g.is_valid:
      g = g.buffer(0)
    return g if (g is not None and not g.is_empty) else None
  except Exception:
    return None


def rasterise_units(units, domain_mask, land_area):
  """Rasterises list of unit dicts onto 4320x2160 uint16 ID grid via PIL ImageDraw."""
  img = Image.new("I", (GRID_W, GRID_H), 0)
  draw = ImageDraw.Draw(img)

  def lonlat_to_px(lon, lat):
    x = (lon + 180.0) * GRID_W / 360.0
    y = (90.0 - lat) * GRID_H / 180.0
    return (x, y)

  # Lower priority painted first (background polities), higher priority painted on top (fine sub-admin HGIS)
  ordered = sorted(units, key=lambda u: (u.get("priority", 0), -u["geom"].area))
  for u in ordered:
    uid = int(u["id"])
    g = u["geom"]
    polys = [g] if isinstance(g, Polygon) else (list(g.geoms) if isinstance(g, MultiPolygon) else [])
    for poly in polys:
      if poly.is_empty:
        continue
      ext = [lonlat_to_px(x, y) for x, y in poly.exterior.coords]
      if len(ext) >= 3:
        draw.polygon(ext, fill=uid)
      for interior in poly.interiors:
        hole = [lonlat_to_px(x, y) for x, y in interior.coords]
        if len(hole) >= 3:
          draw.polygon(hole, fill=0)

  id_grid = np.array(img, dtype=np.int32, copy=True)
  max_id = max((u["id"] for u in units), default=0)
  full_area = np.bincount(id_grid.ravel(), weights=land_area.ravel().astype(np.float64), minlength=max_id + 1)

  id_grid[~domain_mask] = 0
  flat_ids = id_grid[domain_mask]
  flat_la = land_area[domain_mask].astype(np.float64)
  px_cnt = np.bincount(flat_ids, minlength=max_id + 1)
  area_sum = np.bincount(flat_ids, weights=flat_la, minlength=max_id + 1)

  rgba = np.zeros((GRID_H, GRID_W, 4), dtype=np.uint8)
  pos = id_grid > 0
  rgba[pos, 0] = ((id_grid[pos] >> 8) & 0xFF).astype(np.uint8)
  rgba[pos, 1] = (id_grid[pos] & 0xFF).astype(np.uint8)
  rgba[pos, 3] = 255
  return rgba, px_cnt, area_sum, full_area


