def load_frontier_archaeological_candidates(arg0_d_start, arg1_d_end, arg2_country_filter=None):
  """Returns cleaned, verified frontier archaeological & historical settlement candidates for any chapter domain [d_start, d_end]."""
  out = []

  # 1. Canonical Historical Frontier Cities (Xinjiang, Tibet, Hexi/Gansu, Qinghai, Inner Mongolia, Manchuria, Mongolia)
  for nm, alts, ctry, la, lo, fy, pdict, _ in FRONTIER_HISTORICAL_CITIES:
    if arg2_country_filter and ctry != arg2_country_filter:
      continue
    sub = {y: v for y, v in pdict.items() if arg0_d_start <= y <= arg1_d_end}
    if sub:
      out.append({
        "name": nm,
        "other_names": alts,
        "country": ctry,
        "lat": la,
        "lon": lo,
        "foundation_year": fy,
        "population": sub,
        "priority": 9,
        "justification": f"Primary historical frontier city/oasis ({nm}, founded {fy}).",
      })

  # 2. AADR v66 (300 C14-dated ancient-DNA sites across Xinjiang, Tibet, Gansu, Qinghai, Inner Mongolia, Mongolia, Manchuria!)
  aadr_reject = ("burial", "cemetery", "cemeteries", "tomb", "grave", "cave", "site", "kurgan", "barrow", "mound", "sample", "unknown", "unnamed", "province", "district", "region")
  aadr_p = os.path.join(CENSUS_DIR, "aadr_jade_frontier_sites.json")
  if os.path.exists(aadr_p):
    for r in json.load(open(aadr_p, encoding="utf-8")):
      ctry = r.get("country", "China")
      if arg2_country_filter and ctry != arg2_country_filter:
        continue
      lo, la = float(r["lon"]), float(r["lat"])
      if ctry == "China" and lo >= 108.0 and la < 39.5:
        continue
      y0, y1 = int(r["min_yr"]), int(r["max_yr"])
      if min(y1, arg1_d_end) < max(y0, arg0_d_start):
        continue
      raw_nm = str(r["name"] or "")
      raw_nm = re.sub(r"\s*\(.*$", "", raw_nm)
      raw_nm = re.sub(r"[-_]\d{2,4}(?:[-_]\d+)*$", "", raw_nm)
      raw_nm = re.sub(r"\s+(?:I|II|III|IV|V|\d+)$", "", raw_nm)
      nm = clean_name(raw_nm)
      if not nm or len(nm) < 3 or len(nm) > 18 or len(nm.split()) > 2:
        continue
      if any(rk in nm.lower() for rk in aadr_reject) or re.search(r"\d", nm):
        continue
      base = min(3200, 550 + 220 * int(r.get("n_samples", 1)))
      b_yrs = [-3000, -2000, -1500, -1000, -500, -200, 2, 140, 280, 464, 609, 742, 820, 980, 1080, 1102, 1207, 1290, 1393, 1580, 1680, 1776, 1820]
      act = [y for y in b_yrs if max(y0 - 250, arg0_d_start) <= y <= min(y1 + 250, arg1_d_end)]
      if not act:
        mid = max(arg0_d_start, min(arg1_d_end, int(round(0.5 * (y0 + y1)))))
        act = [mid]
      out.append({
        "name": nm,
        "other_names": [],
        "country": ctry,
        "lat": la,
        "lon": lo,
        "foundation_year": y0 - 200,
        "population": {y: base for y in act},
        "priority": 6,
        "justification": f"AADR v66 C14-dated frontier archaeological site ({r['n_samples']} samples, {y0}..{y1}).",
      })

  # 3. Arch Atlas Excavations 2020 (2,296 clean excavated frontier sites across Xinjiang, Tibet, Gansu, Qinghai, Inner Mongolia, Outer Mongolia & Manchuria!)
  aa_reject = (
    "earthwork", "earrthwork", "mine", "reservoir", "factory", "shuinichang", "school",
    "garden", "carving", "cemetery", "cemeteries", "tomb", "grave", "burial", "kiln",
    "yaozhi", "temple", "fosi", "monastery", "cave", "shiku", "bridge", "pagoda", "stupa",
    "inscription", "rock art", "petroglyph", "mound", "barrow", "kurgan", "fossil", "quarry",
    "dam", "canal", "beacon", "tower", "palace", "pavilion", "shrine", "statue", "buddha",
    "road", "ditch", "pit", "hearth", "well", "park", "museum", "station", "airport",
    "university", "hospital", "square", "street", "wangfu", "muqun", "gumu", "site", "ruin",
    "cliff", "hill", "mountain", "lake", "river", "valley", "pass", "wall", "gate", "tower",
    "farm", "ranch", "bridge", "company", "hotel", "building", "hall", "court", "office",
    "district", "sector", "section", "zone", "area", "north ", "south ", "east ", "west ",
  )
  aa_p = os.path.join(CENSUS_DIR, "arch_atlas_jade_frontier.json")
  if os.path.exists(aa_p):
    for r in json.load(open(aa_p, encoding="utf-8")):
      la, lo = float(r["lat"]), float(r["lon"])
      ctry = "Mongolia" if (87.8 <= lo <= 119.5 and 42.5 <= la <= 52.0 and not (lo > 115.0 and la < 46.5)) else "China"
      if arg2_country_filter and ctry != arg2_country_filter:
        continue
      raw_nm = str(r["name"] or "")
      if any(rk in raw_nm.lower() for rk in aa_reject):
        continue
      raw_nm = re.sub(r"\s+(?:Gucheng|Yizhi|Chengzhi|Tuchengzi|Tucheng|Chengzi|Fort|City|Town|Village|I|II|III|IV|V|\d+)$", "", raw_nm, flags=re.I)
      raw_nm = re.sub(r"(?:gucheng|yizhi|chengzhi|tuchengzi|tucheng|chengzi)$", "", raw_nm, flags=re.I)
      nm = clean_name(raw_nm)
      if not nm or len(nm) < 3 or len(nm) > 17 or len(nm.split()) > 2 or re.search(r"\d", nm):
        continue
      desc = str(r.get("desc_hint") or "").lower()
      if any(k in desc for k in ("neolithic", "yangshao", "majiayao", "qijia", "hongshan", "bronze", "xiajiadian", "karuo", "andronovo", "afanasievo", "tarim")):
        y0, y1 = -2500, -500
      elif any(k in desc for k in ("xiongnu", "han ", "silk road", "stein", "hedin", "kucha", "khotan", "loulan", "niya", "turfan", "dunhuang", "juyan", "tarim")):
        y0, y1 = -200, 1200
      elif any(k in desc for k in ("tang", "tibetan", "guge", "bohai", "liao", "jin", "song", "yuan", "mongol", "karakorum", "uyghur", "khitan", "xixia", "tangut")):
        y0, y1 = 600, 1400
      else:
        y0, y1 = -500, 1300
      if min(y1, arg1_d_end) < max(y0, arg0_d_start):
        continue
      b_yrs = [-2000, -1000, -500, -200, 2, 140, 280, 464, 609, 742, 820, 980, 1080, 1102, 1207, 1290, 1393]
      act = [y for y in b_yrs if max(y0, arg0_d_start) <= y <= min(y1, arg1_d_end)]
      if not act:
        continue
      base = 2200 if (lo < 97.0 or la > 42.0) else 2800
      out.append({
        "name": nm,
        "other_names": [r["zh"]] if r.get("zh") else [],
        "country": ctry,
        "lat": la,
        "lon": lo,
        "foundation_year": y0,
        "population": {y: base for y in act},
        "priority": 4,
        "justification": f"Arch Atlas Excavations 2020 frontier archaeological site ({nm}).",
      })

  return out
